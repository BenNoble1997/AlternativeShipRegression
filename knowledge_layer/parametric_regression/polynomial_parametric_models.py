from knowledge_layer.parametric_regression.base_model_fitter_class import BaseModelFitter
from typing import List, Tuple,Optional
import numpy as np
from sklearn.linear_model import LinearRegression, Ridge, Lasso
from sklearn.preprocessing import PolynomialFeatures


"""
Polynomial Parametric Fitter
=============================

Role in the Architecture
-------------------------
This module contains :class:`PolynomialFitter`, a concrete implementation
of
:class:`~knowledge_layer.parametric_regression.base_model_fitter_class.BaseModelFitter`
responsible for all **polynomial regression** models, with or without
regularisation.

It is registered in
:class:`~knowledge_layer.parametric_regression.parametric_model_factory.ModelFactory`
under the key ``'polynomial'``.

Feature Expansion — How Polynomial Regression Works
-----------------------------------------------------
For a dataset with *p* predictors and polynomial degree *d*, sklearn's
:class:`~sklearn.preprocessing.PolynomialFeatures` generates all
monomials up to degree *d*:

    For *p* = 2, *d* = 2: [1, x₁, x₂, x₁², x₁x₂, x₂²]

The number of features after expansion is:

.. math::

    \\binom{p + d}{d} = \\frac{(p+d)!}{p!\\,d!}

For *p* = 3 predictors and *d* = 3 this gives **20 features** from just
3 inputs.  This combinatorial growth means that polynomial models quickly
become over-parameterised relative to typical ship-design datasets, making
regularisation (Ridge or Lasso) essential for degree ≥ 2 with multiple
predictors.

The preprocessor (:class:`~sklearn.preprocessing.PolynomialFeatures`) is
returned from :meth:`~PolynomialFitter.create_and_fit` so that the same
transformation can be applied at prediction time via
:meth:`~PolynomialFitter.predict`.

Regularisation
--------------
The plain ``polynomial-N`` variants use ordinary least squares, which
will overfit if ``n_polynomial_features`` is close to ``n_samples``.
The ``-ridge`` and ``-lasso`` suffixed variants apply L2 and L1 penalties
respectively — see :mod:`multivariable_parametric_models` for a conceptual
overview of regularisation.

Supported Models
----------------
+-------------------------+-------+----------------+
| Model type              | Degree| Regularisation |
+=========================+=======+================+
| ``polynomial-2``        | 2     | None           |
+-------------------------+-------+----------------+
| ``polynomial-3``        | 3     | None           |
+-------------------------+-------+----------------+
| ``polynomial-2-ridge``  | 2     | Ridge (L2)     |
+-------------------------+-------+----------------+
| ``polynomial-2-lasso``  | 2     | Lasso (L1)     |
+-------------------------+-------+----------------+
| ``polynomial-3-ridge``  | 3     | Ridge (L2)     |
+-------------------------+-------+----------------+
| ``polynomial-3-lasso``  | 3     | Lasso (L1)     |
+-------------------------+-------+----------------+
"""


class PolynomialFitter(BaseModelFitter):
    """
    Concrete fitter for polynomial regression models.

    Polynomial features are generated by
    :class:`~sklearn.preprocessing.PolynomialFeatures` and then fitted by
    plain :class:`~sklearn.linear_model.LinearRegression`,
    :class:`~sklearn.linear_model.Ridge`, or
    :class:`~sklearn.linear_model.Lasso` depending on the model type.

    The :class:`~sklearn.preprocessing.PolynomialFeatures` instance is
    returned as the ``preprocessor`` from :meth:`create_and_fit` so that
    prediction on new data can correctly replicate the feature expansion.

    :cvar degree_map: Maps each model-type string to its polynomial degree.
    :vartype degree_map: dict[str, int]

    :cvar regularization_map: Maps each model-type string to its
        regularisation type (``'ridge'``, ``'lasso'``, or ``None``).
    :vartype regularization_map: dict[str, str | None]
    """

    def __init__(self):
        """
        Return all model-type strings handled by this fitter.

        :returns: List of model-type identifiers.
        :rtype: list[str]
        """
        self.degree_map = {
            'polynomial-2': 2, 'polynomial-3': 3,
            'polynomial-2-ridge': 2, 'polynomial-2-lasso': 2,
            'polynomial-3-ridge': 3, 'polynomial-3-lasso': 3,
        }

        self.regularization_map = {
            'polynomial-2': None,
            'polynomial-3': None,
            'polynomial-2-ridge': 'ridge',
            'polynomial-2-lasso': 'lasso',
            'polynomial-3-ridge': 'ridge',
            'polynomial-3-lasso': 'lasso',
        }

    def get_available_models(self) -> List[str]:
        """
        Return all model-type strings handled by this fitter.

        :returns: List of model-type identifiers.
        :rtype: list[str]
        """
        return list(self.degree_map.keys())

    def is_applicable(self, model_type: str, X: np.ndarray, y: np.ndarray,
                      min_samples: int = 5) -> Tuple[bool, str]:
        """
        Check whether a polynomial model can be applied to the data.

        The primary constraint is that the number of samples must exceed
        the number of polynomial features after expansion (otherwise the
        system is underdetermined and OLS has no unique solution; even
        regularised variants become unreliable with very few samples
        relative to feature count).

        Checks applied:

        1. Model-type string must belong to this fitter.
        2. ``n_samples`` must meet *min_samples*.
        3. ``n_samples > n_polynomial_features`` (computed via
           :meth:`_calculate_poly_features`).

        :param model_type: Model-type identifier.
        :type model_type: str
        :param X: Predictor matrix, shape ``(n_samples, n_features)``.
        :type X: numpy.ndarray
        :param y: Target vector, shape ``(n_samples,)``.  Unused here but
            required by the interface.
        :type y: numpy.ndarray
        :param min_samples: Minimum number of required samples.
        :type min_samples: int

        :returns: ``(True, '')`` if applicable; ``(False, reason)``
            otherwise.
        :rtype: tuple[bool, str]
        """

        if model_type not in self.degree_map:
            return False, f"model type '{model_type}' not handled by PolynomialFitter"

        n_samples = len(X)
        n_features = X.shape[1] if len(X.shape) > 1 else 1
        degree = self.degree_map[model_type]

        # Check sample size
        if n_samples < min_samples:
            return False, f"insufficient samples ({n_samples} < {min_samples})"

        # Calculate number of polynomial features
        n_poly_features = self._calculate_poly_features(n_features, degree)

        # Need more samples than features
        if n_samples <= n_poly_features:
            return False, (f"insufficient samples for polynomial degree {degree} "
                           f"({n_samples} samples ≤ {n_poly_features} features)")

        return True, ""

    def create_and_fit(self, model_type: str, X: np.ndarray, y: np.ndarray,
                       alpha: Optional[float] = None, **kwargs):
        """
        Expand features to polynomial space and fit the appropriate model.

        The fitted :class:`~sklearn.preprocessing.PolynomialFeatures`
        instance is returned as the preprocessor so that :meth:`predict`
        can replicate the same transformation on unseen data without
        re-fitting.

        Default alpha values (used when *alpha* is ``None``):

        - Ridge: 1.0
        - Lasso: 0.1

        :param model_type: Model-type identifier.  Must be in
            :attr:`degree_map`.
        :type model_type: str
        :param X: Training predictor matrix, shape
            ``(n_samples, n_features)``.
        :type X: numpy.ndarray
        :param y: Training target vector, shape ``(n_samples,)``.
        :type y: numpy.ndarray
        :param alpha: Regularisation strength for Ridge or Lasso variants.
            When ``None`` a sensible default is applied.
        :type alpha: float, optional
        :param kwargs: Additional keyword arguments (ignored; accepted for
            interface compatibility).

        :returns: ``(model, poly)`` where ``poly`` is the fitted
            :class:`~sklearn.preprocessing.PolynomialFeatures`
            transformer.
        :rtype: tuple[object, PolynomialFeatures]

        :raises ValueError: If ``reg_type`` is not recognised.
        """

        degree = self.degree_map[model_type]
        reg_type = self.regularization_map[model_type]

        # Create polynomial features
        poly = PolynomialFeatures(degree=degree)
        X_poly = poly.fit_transform(X)

        # Fit appropriate model
        if reg_type is None:
            model = LinearRegression()
        elif reg_type == 'ridge':
            alpha = alpha if alpha is not None else 1.0
            model = Ridge(alpha=alpha)
        elif reg_type == 'lasso':
            alpha = alpha if alpha is not None else 0.1
            model = Lasso(alpha=alpha, max_iter=5000)
        else:
            raise ValueError(f"Unknown regularization type: {reg_type}")

        model.fit(X_poly, y)

        return model, poly

    def predict(self, model, preprocessor, X: np.ndarray, model_type: str) -> np.ndarray:
        """
        Transform input features and generate predictions.

        :meth:`PolynomialFeatures.transform` (not ``fit_transform``) is
        called on the preprocessor, ensuring the feature names and column
        order are identical to those seen during fitting.

        :param model: Fitted sklearn estimator.
        :param preprocessor: Fitted
            :class:`~sklearn.preprocessing.PolynomialFeatures` instance
            returned by :meth:`create_and_fit`.
        :param X: Predictor matrix for prediction, shape
            ``(n_samples, n_features)``.
        :type X: numpy.ndarray
        :param model_type: Model-type identifier (unused here; accepted
            for interface compatibility).
        :type model_type: str

        :returns: Predicted values, shape ``(n_samples,)``.
        :rtype: numpy.ndarray
        """
        X_poly = preprocessor.transform(X)
        return model.predict(X_poly)

    def get_n_parameters(self, model_type: str, X: np.ndarray,
                         fitted_model=None) -> int:
        """
        Return the effective number of free parameters.

        For Lasso variants, if ``fitted_model`` is provided the count
        equals the number of non-zero coefficients plus one (intercept).
        This sparse count is essential for correct AIC / BIC calculation —
        using the full polynomial feature count would over-penalise the
        sparsity that Lasso achieves.

        For Ridge and plain polynomial variants all polynomial features
        are considered active, so the count is the full expansion size.

        :param model_type: Model-type identifier.
        :type model_type: str
        :param X: Predictor matrix used to determine the input feature
            count, shape ``(n_samples, n_features)``.
        :type X: numpy.ndarray
        :param fitted_model: Fitted sklearn estimator.  When supplied and
            ``model_type`` contains ``'lasso'``, the non-zero coefficient
            count is returned instead of the full polynomial feature count.
            Defaults to ``None``.

        :returns: Effective number of parameters (including intercept).
        :rtype: int
        """
        n_features = X.shape[1] if len(X.shape) > 1 else 1
        degree = self.degree_map[model_type]

        # ✅ Check if Lasso with fitted model
        if fitted_model is not None and 'lasso' in model_type:
            # Count non-zero coefficients
            if hasattr(fitted_model, 'coef_'):
                active_count = np.sum(np.abs(fitted_model.coef_) > 1e-10)
                return active_count + 1  # +1 for intercept

        # Default: calculate total polynomial features
        return self._calculate_poly_features(n_features, degree)



    def get_model_description(self, model_type: str) -> str:
        """
        Return a concise description including the functional form.

        :param model_type: Model-type identifier.
        :type model_type: str

        :returns: Human-readable description.
        :rtype: str
        """
        degree = self.degree_map[model_type]
        reg_type = self.regularization_map[model_type]

        if degree == 2:
            base_desc = 'Quadratic: y = β₀ + β₁·x + β₂·x² + β₃·x·y + ...'
        elif degree == 3:
            base_desc = 'Cubic: y = β₀ + β₁·x + β₂·x² + β₃·x³ + ...'
        else:
            base_desc = f'Polynomial degree {degree}'

        if reg_type:
            return f'{base_desc} with {reg_type.upper()} regularization'
        return base_desc

    def _calculate_poly_features(self, n_features: int, degree: int) -> int:
        """
        Calculate the number of features after polynomial expansion.

        Uses the combinatorial formula for the number of monomials of
        degree *at most* ``degree`` in ``n_features`` variables:

        .. math::

            \\sum_{d=0}^{\\text{degree}} \\binom{n + d - 1}{d}

        This includes the constant term (degree 0), all linear terms
        (degree 1), all quadratic monomials (degree 2), and so on.

        :param n_features: Number of input features before expansion.
        :type n_features: int
        :param degree: Polynomial degree.
        :type degree: int

        :returns: Total number of polynomial features (including
            the constant term).
        :rtype: int
        """
        from math import comb
        return sum(comb(n_features + d - 1, d) for d in range(degree + 1))